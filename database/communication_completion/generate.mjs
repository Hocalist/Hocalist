// Generates the guarded communications-completion rollout bundle from the
// source migrations. Local-only: reads files and writes the bundle. Never
// connects to a database. Run: node database/communication_completion/generate.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const read = (name) => readFileSync(join(here, name), 'utf8').replace(/\r\n/g, '\n');

const MIGRATIONS = [
  '150_chat_block.sql',
  '151_chat_search.sql',
  '152_call_status.sql',
  '153_communication_producers.sql',
  '154_chat_realtime_signals.sql',
  '155_media_block_fence.sql',
];

function migrationBody(name) {
  const text = read(name);
  const start = text.indexOf('\nBEGIN;');
  const end = text.lastIndexOf('COMMIT;');
  if (start < 0 || end < start) throw new Error(`${name} must wrap its body in BEGIN;/COMMIT;`);
  const body = text.slice(start + '\nBEGIN;'.length, end).trim();
  return `-- ---------------------------------------------------------------------------\n-- ${name}\n-- ---------------------------------------------------------------------------\n${body}`;
}

const guard = read('guard.sql').trim();
const verify = read('verify_block.sql').trim();

const header = (title) =>
  `-- GENERATED by database/communication_completion/generate.mjs. Do not edit by hand.\n-- ${title}\n`;

const preflight = `${header('Read-only communications-completion preflight.')}
BEGIN READ ONLY;
SET LOCAL statement_timeout = '15s';
${guard}
SELECT 'PASS: communications-completion prerequisites intact and objects absent' AS communication_preflight;
ROLLBACK;
`;

const apply = `${header('Apply the communications-completion bundle in one transaction.')}
BEGIN;
SET LOCAL lock_timeout = '5s';
SET LOCAL statement_timeout = '60s';
${guard}
${MIGRATIONS.map(migrationBody).join('\n')}
${verify}
COMMIT;
`;

const verifySql = `${header('Read-only communications-completion verification.')}
BEGIN READ ONLY;
SET LOCAL statement_timeout = '15s';
${verify}
SELECT 'PASS: communications-completion installed and contained' AS communication_verify;
ROLLBACK;
`;

writeFileSync(join(here, 'rollout', 'preflight.sql'), preflight);
writeFileSync(join(here, 'rollout', 'apply.sql'), apply);
writeFileSync(join(here, 'rollout', 'verify.sql'), verifySql);
console.log('generated rollout/preflight.sql, rollout/apply.sql, rollout/verify.sql');
