// Shared generator helpers for small guarded rollout bundles.
//
// Generators run against disposable PGlite only and never open a live
// connection. A bundle has four reviewable files:
//   preflight.sql - read-only prerequisite/absence guard
//   apply.sql     - one transaction: inline guard, migrations, verification
//   verify.sql    - read-only post-apply verification
//   containment.sql - grants-only withdrawal written by the caller
import { mkdir, writeFile } from 'node:fs/promises';

export const normalize = (text) => text.replace(/\r\n/g, '\n');
export const quote = (value) => "'" + value.replaceAll("'", "''") + "'";

/** Removes the outer BEGIN;/COMMIT; wrapper so a migration can be embedded. */
export function migrationBody(text, name) {
  const normalized = normalize(text);
  const start = normalized.indexOf('\nBEGIN;');
  const end = normalized.lastIndexOf('COMMIT;');
  if (start < 0 || end < start) {
    throw new Error(`${name} must wrap its body in BEGIN;/COMMIT;`);
  }
  return normalized.slice(start + '\nBEGIN;'.length, end).trim();
}

export async function functionHash(db, signature) {
  const { rows } = await db.query(
    "SELECT md5(replace(pg_get_functiondef(to_regprocedure($1)),chr(13),'')) AS hash",
    [signature],
  );
  return rows[0]?.hash ?? null;
}

export async function functionHashes(db, signatures) {
  const hashes = new Map();
  for (const signature of signatures) {
    hashes.set(signature, await functionHash(db, signature));
  }
  return hashes;
}

/**
 * Exact-definition prerequisite checks, CR/LF normalized like the packages.
 * Each value is one hash or an array of acceptable hashes, so bundles that can
 * legitimately be applied in either order (media 101 / chat 011 media_gateway)
 * accept every reviewed body.
 */
export function driftGuard(hashes) {
  return [...hashes.entries()]
    .map(([signature, value]) => {
      const accepted = Array.isArray(value) ? value : [value];
      return `IF to_regprocedure(${quote(signature)}) IS NULL OR NOT (md5(replace(pg_get_functiondef(to_regprocedure(${quote(signature)})),chr(13),'')) = ANY(ARRAY[${accepted.map(quote).join(',')}]::text[])) THEN RAISE EXCEPTION 'Prerequisite drift: ${signature}'; END IF;`;
    })
    .join('\n');
}

/** Missing-relation and missing-column prerequisite checks. */
export function presenceGuard(checks) {
  return checks
    .map(
      ({ test, label }) =>
        `IF NOT (${test}) THEN RAISE EXCEPTION 'Missing prerequisite: ${label}'; END IF;`,
    )
    .join('\n');
}

/** Partial-installation checks: each entry is a boolean "already exists" test. */
export function absenceGuard(checks) {
  return checks
    .map(
      ({ test, label }) =>
        `IF (${test}) THEN RAISE EXCEPTION 'Already installed or partial installation: ${label}'; END IF;`,
    )
    .join('\n');
}

/** Post-apply function definition checks plus admin-independent grant matrix. */
export function functionVerify(hashes, grants = {}) {
  const lines = [];
  for (const [signature, hash] of hashes) {
    lines.push(
      `f:=to_regprocedure(${quote(signature)});\nIF f IS NULL OR md5(replace(pg_get_functiondef(f),chr(13),''))<>${quote(hash)} THEN RAISE EXCEPTION 'Function drift: ${signature}'; END IF;`,
    );
    const roles = grants[signature];
    if (roles) {
      lines.push(
        `FOR r IN SELECT unnest(ARRAY['anon','authenticated','service_role']) LOOP IF has_function_privilege(r,f,'EXECUTE') IS DISTINCT FROM (r=ANY(ARRAY[${roles.map(quote).join(',')}]::text[])) THEN RAISE EXCEPTION 'Function privilege drift: ${signature} %',r; END IF; END LOOP;`,
      );
    }
  }
  return lines.join('\n');
}

/**
 * Writes the four bundle files. `preflight`/`verify` are the DO-block bodies,
 * `containment` is the full containment transaction.
 */
export async function writeBundle(
  base,
  { generator, title, preflight, body, verify, containment, directory = 'rollout/' },
) {
  const header = `-- GENERATED by ${generator}. Do not edit by hand.\n-- ${title}\n`;
  const target = new URL(directory, base);
  await mkdir(target, { recursive: true });
  await writeFile(
    new URL(`${directory}preflight.sql`, base),
    `${header}BEGIN READ ONLY;\nSET LOCAL statement_timeout = '15s';\nDO $guard$ BEGIN\n${preflight}\nEND $guard$;\nROLLBACK;\n`,
  );
  await writeFile(
    new URL(`${directory}apply.sql`, base),
    `${header}BEGIN;\nSET LOCAL lock_timeout = '5s';\nSET LOCAL statement_timeout = '60s';\nDO $guard$ BEGIN\n${preflight}\nEND $guard$;\n${body}\nDO $verify$ DECLARE f oid; r text; BEGIN\n${verify}\nEND $verify$;\nCOMMIT;\n`,
  );
  await writeFile(
    new URL(`${directory}verify.sql`, base),
    `${header}BEGIN READ ONLY;\nSET LOCAL statement_timeout = '15s';\nDO $verify$ DECLARE f oid; r text; BEGIN\n${verify}\nEND $verify$;\nROLLBACK;\n`,
  );
  await writeFile(new URL(`${directory}containment.sql`, base), `${header}${containment}\n`);
}
